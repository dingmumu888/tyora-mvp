const patterns: Array<[RegExp, (...values: string[]) => string]> = [
  [/^(\d+) items need a reply$/, (count) => `${count} 条记录需要回复`],
  [/^(\d+) files?$/, (count) => `${count} 个文件`],
  [/^(\d+) comments?$/, (count) => `${count} 条评论`],
  [/^(\d+) helpful$/, (count) => `${count} 个有帮助`],
  [/^(\d+) interested$/, (count) => `${count} 人感兴趣`],
  [/^Reference images: (\d+)$/, (count) => `参考图片：${count}`],
  [/^Reference image (\d+)$/, (count) => `参考图片 ${count}`],
  [/^Homepage #(.+)$/, (order) => `首页精选 #${order}`],
  [/^(\d+) current environment records?$/, (count) => `${count} 条正式环境记录`],
  [/^(\d+) Production records?$/, (count) => `${count} 条正式环境记录`],
  [/^Open (.+) submission$/, (title) => `打开“${translateAdminText("zh", title)}”提交记录`]
];

export function translateAdminText(language: AdminLanguage, text: string) {
  if (language !== "zh" || !text) return text;
  const trimmed = text.trim();
  const direct = zh[trimmed];
  if (direct) return text.replace(trimmed, direct);
  for (const [pattern, render] of patterns) {
    const match = trimmed.match(pattern);
    if (match) return text.replace(trimmed, render(...match.slice(1)));
  }
  return text;
}

export function hasAdminTranslation(text: string) {
  return Boolean(zh[text.trim()]);
}
